def replace_para(p, new_text):
    """替换段落文字，保留第一个 run 的格式。"""
    if not p.runs:
        p.add_run(new_text)
        return
    p.runs[0].text = new_text
    for r in p.runs[1:]:
        r._element.getparent().remove(r._element)


def main():
    doc = Document(SRC)
    if len(doc.paragraphs) < 100:
        raise SystemExit("段落数异常：%d" % len(doc.paragraphs))

    for idx, (old_brief, new_text, reason) in CHANGES.items():
        p = doc.paragraphs[idx]
        # 按段索引替换：原文里的全角空格、\xa0 等特殊字符会让文本匹配失败，
        # 段落顺序已逐段核对过（100 段），因此直接用索引。
        if old_brief and old_brief[:6] not in p.text:
            print("⚠️ 段 %d 原文首句与记录略有差异，仍按索引替换" % idx)
        replace_para(p, new_text)
        print("已改段 %d：%s" % (idx, new_text[:36]))

    doc.save(OUT_DOCX)
    print("\n修订版已保存：", OUT_DOCX)

    # ---------- 对照表 ----------
    tdoc = Document()
    sec = tdoc.sections[0]
    sec.left_margin = Cm(1.8)
    sec.right_margin = Cm(1.8)
    style = tdoc.styles["Normal"]
    style.font.name = "宋体"
    style.font.size = Pt(9)
    style.element.rPr.rFonts.set(__import__("docx").oxml.ns.qn("w:eastAsia"), "宋体")

    t = tdoc.add_paragraph()
    r = t.add_run("《开发全过程解说》修改对照表")
    r.font.size = Pt(16)
    r.font.bold = True

    intro = tdoc.add_paragraph()
    intro.add_run("说明：仅修改与作品实际情况不符的内容（技术栈、不存在的模块、无出处数据），"
                  "保留原文十一部分结构与宣讲口吻。下表中“段号”对应原文档段落顺序。")

    table = tdoc.add_table(rows=1, cols=4)
    table.style = "Table Grid"
    headers = ["段号", "原文要点", "改为", "原因"]
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        rr = cell.paragraphs[0].add_run(h)
        rr.font.bold = True
        rr.font.size = Pt(9)

    for idx in sorted(CHANGES):
        old_brief, new_text, reason = CHANGES[idx]
        cells = table.add_row().cells
        cells[0].text = str(idx)
        cells[1].text = old_brief
        cells[2].text = new_text
        cells[3].text = reason
        for c in cells:
            for p in c.paragraphs:
                for run in p.runs:
                    run.font.size = Pt(8)

    widths = [Cm(1.2), Cm(6.4), Cm(6.4), Cm(3.6)]
    for i, w in enumerate(widths):
        for row in table.rows:
            row.cells[i].width = w
    table.autofit = False

    tdoc.save(OUT_TABLE)
    print("对照表已保存：", OUT_TABLE)
    print("共修改 %d 处" % len(CHANGES))


if __name__ == "__main__":
    main()
